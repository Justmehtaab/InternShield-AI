create table if not exists public.saved_reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  data jsonb not null,
  created_at timestamptz not null default now()
);

alter table public.saved_reviews enable row level security;

drop policy if exists "Users can read their own reviews" on public.saved_reviews;
create policy "Users can read their own reviews"
  on public.saved_reviews for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users can insert their own reviews" on public.saved_reviews;
create policy "Users can insert their own reviews"
  on public.saved_reviews for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "Users can delete their own reviews" on public.saved_reviews;
create policy "Users can delete their own reviews"
  on public.saved_reviews for delete
  to authenticated
  using (auth.uid() = user_id);
